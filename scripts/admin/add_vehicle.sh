#!/usr/bin/env bash
#
# add_vehicle.sh - register a new vehicle identity in a signaling server config.
#
# Usage:
#   add_vehicle.sh --id VEHICLE_ID --config YAML_PATH
#                  [--secrets-dir DIR] [--assign-to-driver DRIVER_ID]...
#                  [--force] [--dry-run] [--help]
#
# The script generates a 32-byte hex device token, stores it with mode 0600, adds
#
#   auth:
#     vehicles:
#       - id: <vehicle-id>
#         device_token_file: secrets/<vehicle-id>.token
#
# to the signaling server YAML, and optionally appends the vehicle to the
# `vehicles` permission list of one or more drivers under `auth.drivers`.
#
# Guarantees:
#   * vehicle ids are rejected when they already exist (the server refuses to
#     start on duplicates);
#   * `device_token_file` is written relative to the YAML directory, which is how
#     the server resolves relative secret paths;
#   * the YAML is edited on a sibling temporary copy and only moved into place
#     after `mine-teleop-signaling-server --validate-config` accepts it; a missing
#     validator, missing secret environment variable, or any validation error is
#     fatal;
#   * a token generated by a run that later fails is removed again.
#
# YAML editing backend: `yq` (https://github.com/mikefarah/yq, v4) when present,
# otherwise a python3 + PyYAML fallback that inserts lines in place. Both keep
# surrounding comments and formatting intact.
#
# Environment:
#   MINE_TELEOP_SIGNALING_BIN  explicit path to mine-teleop-signaling-server
#   MINE_TELEOP_BUILD_DIR      build directory searched for the server binary
#   NO_COLOR                   disable colored output
#
set -euo pipefail
umask 077

script_dir="$(CDPATH= cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
repo_root="$(CDPATH= cd -- "$script_dir/../.." && pwd)"

if [[ -t 1 && -z "${NO_COLOR:-}" ]]; then
  color_red=$'\033[31m'
  color_green=$'\033[32m'
  color_yellow=$'\033[33m'
  color_blue=$'\033[34m'
  color_bold=$'\033[1m'
  color_reset=$'\033[0m'
else
  color_red="" color_green="" color_yellow="" color_blue="" color_bold="" color_reset=""
fi

step() { printf '%s==>%s %s\n' "$color_blue" "$color_reset" "$*"; }
note() { printf '    %s\n' "$*"; }
ok() { printf '%s ok %s %s\n' "$color_green" "$color_reset" "$*"; }
warn() { printf '%swarn%s %s\n' "$color_yellow" "$color_reset" "$*" >&2; }
fail() { printf '%sfail%s %s\n' "$color_red" "$color_reset" "$*" >&2; exit 2; }

path_mode() {
  stat -c '%a' -- "$1" 2>/dev/null || stat -f '%Lp' -- "$1"
}

path_owner() {
  stat -c '%u' -- "$1" 2>/dev/null || stat -f '%u' -- "$1"
}

normalize_managed_path() {
  local candidate="$1" label="$2" lexical physical
  lexical="$(realpath -ms -- "$candidate")" ||
    fail "cannot normalize $label path: $candidate"
  physical="$(realpath -m -- "$candidate")" ||
    fail "cannot resolve $label path: $candidate"
  [[ "$physical" == "$lexical" ]] ||
    fail "$label path must not contain symbolic links: $candidate"
  printf '%s\n' "$lexical"
}

verify_managed_path() {
  local candidate="$1" label="$2" lexical physical
  lexical="$(realpath -ms -- "$candidate")" ||
    fail "cannot normalize $label path: $candidate"
  physical="$(realpath -m -- "$candidate")" ||
    fail "cannot resolve $label path: $candidate"
  [[ "$physical" == "$lexical" ]] ||
    fail "$label path became symbolic-link based: $candidate"
}

check_owned_directory() {
  local directory="$1" label="$2" mode owner
  [[ ! -L "$directory" ]] || fail "$label must not be a symbolic link: $directory"
  [[ -d "$directory" ]] || fail "$label is not a directory: $directory"
  owner="$(path_owner "$directory")" || fail "cannot read owner of $label: $directory"
  [[ "$owner" == "$EUID" ]] ||
    fail "$label must be owned by uid $EUID (found uid $owner): $directory"
  mode="$(path_mode "$directory")" || fail "cannot read mode of $label: $directory"
  [[ "$mode" =~ ^[0-7]{3,4}$ ]] || fail "cannot parse mode '$mode' for $label: $directory"
  (( (8#$mode & 0022) == 0 )) ||
    fail "$label must not be group- or world-writable (mode $mode): $directory"
  [[ -w "$directory" ]] || fail "$label is not writable: $directory"
}

harden_private_directory() {
  local directory="$1" label="$2"
  verify_managed_path "$directory" "$label"
  check_owned_directory "$directory" "$label"
  chmod 0700 "$directory"
  [[ "$(path_mode "$directory")" == '700' ]] ||
    fail "$label could not be restricted to mode 0700: $directory"
}

usage() {
  cat <<'EOF'
Usage:
  add_vehicle.sh --id VEHICLE_ID --config YAML_PATH [options]

Required:
  --id VEHICLE_ID              vehicle identity to register, e.g. vehicle-003
  --config YAML_PATH           signaling server multi-identity YAML

Options:
  --secrets-dir DIR            token directory (default: <yaml dir>/secrets)
  --backup-dir DIR             config backup directory (default: <yaml dir>/backups)
  --assign-to-driver DRIVER_ID append the vehicle to this driver's permission
                               list; may be repeated
  --force                      overwrite an existing token file
  --dry-run                    render and report the plan without changing YAML,
                               credentials, or backups
  --help                       show this help

Examples:
  add_vehicle.sh --id vehicle-003 --config /etc/mine-teleop/signaling-server.yaml
  add_vehicle.sh --id vehicle-003 --config configs/signaling-server.2x2.dev.yaml \
      --assign-to-driver driver-console-001 --dry-run
EOF
}

