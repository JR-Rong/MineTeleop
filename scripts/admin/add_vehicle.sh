cleanup() {
  [[ -z "$temporary_config" ]] || rm -f -- "$temporary_config"
  [[ -z "$token_staging" ]] || rm -f -- "$token_staging"
  if [[ "$committed" != "yes" && "$created_token" == "yes" ]]; then
    if [[ "$token_existed_before" == "yes" && -n "$token_rollback" ]]; then
      mv -f -- "$token_rollback" "$token_path"
      token_rollback=""
      warn "restored the previous token because the config was not updated"
    else
      rm -f -- "$token_path"
      warn "removed the freshly generated token $token_path because the config was not updated"
    fi
  fi
  [[ -z "$token_rollback" ]] || rm -f -- "$token_rollback"
  if [[ "$committed" != "yes" && "$created_secrets_dir" == "yes" ]]; then
    rmdir -- "$secrets_dir" 2>/dev/null || true
  fi
  return 0
}
trap cleanup EXIT

render_candidate() {
  local target="$1" driver
  cat -- "$config_path" >"$target"
  yaml_add_vehicle "$target" "$vehicle_id" "$token_reference"
  for driver in ${assign_drivers[@]+"${assign_drivers[@]}"}; do
    yaml_assign_vehicle "$target" "$driver" "$vehicle_id"
  done

  if [[ "$(yaml_ids "$target" vehicles | grep -c -x -F -- "$vehicle_id")" != "1" ]]; then
    fail "the rendered config does not contain exactly one '$vehicle_id' vehicle; $config_path is unchanged"
  fi
  for driver in ${assign_drivers[@]+"${assign_drivers[@]}"}; do
    if ! yaml_driver_vehicles "$target" "$driver" | grep -q -x -F -- "$vehicle_id"; then
      fail "driver $driver did not gain $vehicle_id in the rendered config; $config_path is unchanged"
    fi
  done
}

